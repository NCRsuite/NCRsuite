CREATE OR REPLACE FUNCTION public.public_booking_client_portal_activation_status(p_token uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'private', 'pg_catalog'
AS $function$
declare
  v_appointment public.appointments%rowtype;
  v_client public.clients%rowtype;
  v_company public.organization_companies%rowtype;
  v_active boolean := false;
  v_pending boolean := false;
  v_email text;
  v_masked text;
begin
  select * into v_appointment
  from public.appointments
  where public_token=p_token
    and source='public'
  limit 1;

  if v_appointment.id is null then return null; end if;

  select * into v_client
  from public.clients
  where organization_id=v_appointment.organization_id
    and id=v_appointment.client_id
    and status='active';

  if v_client.id is null then return null; end if;

  select * into v_company
  from public.organization_companies
  where organization_id=v_appointment.organization_id
    and id=v_appointment.company_id
    and status='active';

  v_email:=nullif(lower(trim(coalesce(v_client.email,''))),'');
  if v_email is not null then
    v_masked:=regexp_replace(v_email,'^(.{1,2}).*(@.*)$','\1••••\2');
  end if;

  select exists(
    select 1
    from public.coiffure_client_portal_accounts a
    where a.organization_id=v_appointment.organization_id
      and a.client_id=v_client.id
      and a.status='active'
      and (v_email is null or lower(a.email)=v_email)
  ) into v_active;

  select exists(
    select 1
    from public.coiffure_client_portal_invitations i
    where i.organization_id=v_appointment.organization_id
      and i.client_id=v_client.id
      and i.status='pending'
      and i.expires_at>now()
      and (v_email is null or lower(i.email)=v_email)
  ) into v_pending;

  return jsonb_build_object(
    'available', private.coiffure_client_portal_company_feature_enabled(v_appointment.organization_id,v_appointment.company_id) and v_email is not null,
    'already_active',v_active,
    'invitation_pending',v_pending,
    'masked_email',v_masked,
    'company_name',coalesce(v_company.name,'Votre enseigne')
  );
end;
$function$;

CREATE OR REPLACE FUNCTION public.request_public_booking_client_portal_activation(p_token uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'private', 'pg_catalog'
AS $function$
declare
  v_appointment public.appointments%rowtype;
  v_client public.clients%rowtype;
  v_company public.organization_companies%rowtype;
  v_email text;
  v_auth_email text;
  v_existing_account uuid;
  v_invitation_id uuid;
  v_token text;
  v_masked text;
begin
  select * into v_appointment
  from public.appointments
  where public_token=p_token
    and source='public'
  for update;

  if v_appointment.id is null then raise exception 'Réservation introuvable.'; end if;
  if not private.coiffure_client_portal_company_feature_enabled(v_appointment.organization_id,v_appointment.company_id) then
    raise exception 'L’espace client est actuellement indisponible.';
  end if;

  select * into v_client
  from public.clients
  where organization_id=v_appointment.organization_id
    and id=v_appointment.client_id
    and status='active';

  if v_client.id is null then raise exception 'Dossier client introuvable.'; end if;

  select * into v_company
  from public.organization_companies
  where organization_id=v_appointment.organization_id
    and id=v_appointment.company_id
    and status='active';

  v_email:=nullif(lower(trim(coalesce(v_client.email,''))),'');
  if v_email is null then
    raise exception 'Ajoutez une adresse e-mail à votre dossier pour activer l’espace client.';
  end if;
  v_masked:=regexp_replace(v_email,'^(.{1,2}).*(@.*)$','\1••••\2');

  select a.id into v_existing_account
  from public.coiffure_client_portal_accounts a
  where a.organization_id=v_appointment.organization_id
    and a.client_id=v_client.id
    and lower(a.email)=v_email
    and a.status='active'
  order by a.updated_at desc
  limit 1;

  if v_existing_account is not null then
    return jsonb_build_object('status','active','masked_email',v_masked,'company_name',coalesce(v_company.name,'Votre enseigne'));
  end if;

  if auth.uid() is not null then
    select lower(email) into v_auth_email from auth.users where id=auth.uid();
    if v_auth_email=v_email then
      insert into public.coiffure_client_portal_accounts(organization_id,client_id,user_id,email,display_name,status,last_seen_at)
      values(
        v_appointment.organization_id,v_client.id,auth.uid(),v_email,
        trim(concat_ws(' ',v_client.first_name,v_client.last_name)),'active',now()
      )
      on conflict(organization_id,client_id,user_id)
      do update set email=excluded.email,status='active',last_seen_at=now(),updated_at=now();

      perform public.apply_coiffure_welcome_benefit(v_appointment.organization_id,v_client.id);
      perform public.ensure_coiffure_birthday_reward(v_appointment.organization_id,v_client.id);

      insert into public.audit_logs(organization_id,user_id,action,entity_type,entity_id,metadata)
      values(
        v_appointment.organization_id,auth.uid(),'coiffure.client_portal_self_activated','client',v_client.id::text,
        jsonb_build_object('company_id',v_appointment.company_id,'appointment_id',v_appointment.id)
      );

      return jsonb_build_object('status','active','masked_email',v_masked,'company_name',coalesce(v_company.name,'Votre enseigne'));
    end if;
  end if;

  if (
    select count(*)
    from public.coiffure_client_portal_invitations i
    where i.organization_id=v_appointment.organization_id
      and i.client_id=v_client.id
      and lower(i.email)=v_email
      and i.invitation_source='public_booking'
      and i.created_at>now()-interval '24 hours'
  )>=3 then
    raise exception 'Plusieurs e-mails d’activation ont déjà été envoyés. Réessayez plus tard.';
  end if;

  select i.id into v_invitation_id
  from public.coiffure_client_portal_invitations i
  where i.organization_id=v_appointment.organization_id
    and i.client_id=v_client.id
    and lower(i.email)=v_email
    and i.status='pending'
    and i.expires_at>now()
    and i.created_at>now()-interval '5 minutes'
  order by i.created_at desc
  limit 1;

  if v_invitation_id is not null then
    return jsonb_build_object('status','sent','masked_email',v_masked,'company_name',coalesce(v_company.name,'Votre enseigne'));
  end if;

  update public.coiffure_client_portal_invitations
  set status='revoked',revoked_at=now(),updated_at=now()
  where organization_id=v_appointment.organization_id
    and client_id=v_client.id
    and lower(email)=v_email
    and status='pending';

  v_token:=encode(extensions.gen_random_bytes(32),'hex');

  insert into public.coiffure_client_portal_invitations(
    organization_id,client_id,email,display_name,token_hash,status,expires_at,invited_by,invitation_source
  )
  values(
    v_appointment.organization_id,v_client.id,v_email,
    trim(concat_ws(' ',v_client.first_name,v_client.last_name)),
    extensions.digest(v_token,'sha256'),'pending',now()+interval '7 days',null,'public_booking'
  )
  returning id into v_invitation_id;

  perform public.enqueue_coiffure_client_portal_invitation_email(v_invitation_id,v_token);

  insert into public.audit_logs(organization_id,user_id,action,entity_type,entity_id,metadata)
  values(
    v_appointment.organization_id,null,'coiffure.client_portal_activation_requested','client',v_client.id::text,
    jsonb_build_object('company_id',v_appointment.company_id,'appointment_id',v_appointment.id,'invitation_id',v_invitation_id)
  );

  return jsonb_build_object('status','sent','masked_email',v_masked,'company_name',coalesce(v_company.name,'Votre enseigne'));
end;
$function$;

CREATE OR REPLACE FUNCTION public.reschedule_public_booking_v3(p_token uuid, p_site_id uuid, p_staff_id uuid, p_starts_at timestamp with time zone)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'pg_catalog'
AS $function$
declare
  v_appointment public.appointments%rowtype;
  v_org public.organizations%rowtype;
  v_company public.organization_companies%rowtype;
  v_service_ids uuid[];
  v_item_count integer;
  v_timezone text;
  v_ends_at timestamptz;
  v_staff_name text;
  v_status text;
  v_service_label text;
begin
  select * into v_appointment
  from public.appointments
  where public_token=p_token and source='public'
  for update;

  if v_appointment.id is null then raise exception 'Réservation introuvable.'; end if;

  select * into v_org from public.organizations where id=v_appointment.organization_id;
  if not public.plan_feature_enabled(v_org.plan,'online_booking_management') then
    raise exception 'La modification en ligne n’est pas incluse dans la formule de cet établissement.';
  end if;
  if v_appointment.status not in ('pending','confirmed') then
    raise exception 'Cette réservation ne peut plus être déplacée en ligne.';
  end if;
  if now()>=v_appointment.starts_at-make_interval(hours=>v_org.booking_cancel_notice_hours) then
    raise exception 'Le délai de modification en ligne est dépassé.';
  end if;

  select count(*)::integer,array_agg(asi.service_id order by asi.position)
  into v_item_count,v_service_ids
  from public.appointment_service_items asi
  where asi.appointment_id=v_appointment.id;

  if coalesce(v_item_count,0)=0 then
    return public.reschedule_public_booking_v2(p_token,p_site_id,p_staff_id,p_starts_at);
  end if;

  if p_site_id is distinct from v_appointment.site_id then
    raise exception 'Le déplacement doit rester dans l’établissement initial.';
  end if;

  select * into v_company
  from public.organization_companies
  where id=v_appointment.company_id
    and organization_id=v_appointment.organization_id
    and status='active';
  if v_company.id is null or v_company.public_slug is null then
    raise exception 'L’enseigne de cette réservation est indisponible.';
  end if;

  select s.timezone into v_timezone
  from public.organization_sites s
  where s.id=p_site_id
    and s.organization_id=v_appointment.organization_id
    and s.company_id=v_company.id
    and s.status='active';
  if v_timezone is null then raise exception 'L’établissement est indisponible.'; end if;

  select st.display_name into v_staff_name
  from public.staff st
  where st.id=p_staff_id
    and st.organization_id=v_appointment.organization_id
    and st.company_id=v_company.id
    and st.site_id=p_site_id
    and st.active=true;
  if v_staff_name is null then raise exception 'Ce professionnel n’est pas disponible dans cet établissement.'; end if;

  perform pg_advisory_xact_lock(hashtextextended(p_staff_id::text,0));

  update public.appointments
  set status='cancelled'
  where id=v_appointment.id;

  select available.slot_end
  into v_ends_at
  from public.get_public_metier_coiffure_company_multi_slots(
    v_company.public_slug,
    p_site_id,
    v_service_ids,
    (p_starts_at at time zone v_timezone)::date,
    p_staff_id
  ) available
  where available.staff_id=p_staff_id
    and available.slot_start=p_starts_at
  limit 1;

  if v_ends_at is null then
    raise exception 'Ce créneau n’est plus disponible. Choisissez une autre heure.';
  end if;

  v_status:=case when v_org.booking_confirmation_mode='manual' then 'pending' else 'confirmed' end;

  update public.appointments
  set staff_id=p_staff_id,
      starts_at=p_starts_at,
      ends_at=v_ends_at,
      status=v_status,
      cancelled_at=null,
      cancellation_reason=null,
      updated_at=now()
  where id=v_appointment.id;

  with ordered as (
    select asi.id,
           asi.position,
           asi.price_cents,
           s.name,
           s.duration_minutes,
           coalesce(s.booking_buffer_before_minutes,0) buffer_before_minutes,
           coalesce(s.booking_buffer_after_minutes,0) buffer_after_minutes,
           coalesce(
             sum(s.duration_minutes) over (
               order by asi.position
               rows between unbounded preceding and 1 preceding
             ),0
           )::integer offset_minutes
    from public.appointment_service_items asi
    join public.services s
      on s.id=asi.service_id
     and s.organization_id=asi.organization_id
     and s.company_id=asi.company_id
     and s.active=true
     and s.online_booking_enabled=true
    where asi.appointment_id=v_appointment.id
  )
  update public.appointment_service_items asi
  set staff_id=p_staff_id,
      service_name=o.name,
      duration_minutes=o.duration_minutes,
      buffer_before_minutes=o.buffer_before_minutes,
      buffer_after_minutes=o.buffer_after_minutes,
      starts_at=p_starts_at+make_interval(mins=>o.offset_minutes),
      ends_at=p_starts_at+make_interval(mins=>o.offset_minutes+o.duration_minutes)
  from ordered o
  where asi.id=o.id;

  select string_agg(asi.service_name,' + ' order by asi.position)
  into v_service_label
  from public.appointment_service_items asi
  where asi.appointment_id=v_appointment.id;

  insert into public.audit_logs(organization_id,user_id,action,entity_type,entity_id,metadata)
  values(
    v_appointment.organization_id,null,'appointment.public_rescheduled','appointment',v_appointment.id::text,
    jsonb_build_object('company_id',v_company.id,'service_count',v_item_count)
  );

  return jsonb_build_object(
    'appointment_id',v_appointment.id,
    'token',p_token,
    'status',v_status,
    'starts_at',p_starts_at,
    'ends_at',v_ends_at,
    'organization_name',v_org.name,
    'organization_slug',v_org.slug,
    'company_slug',v_company.public_slug,
    'service_name',v_service_label,
    'staff_name',v_staff_name,
    'amount_cents',v_appointment.amount_cents
  );
exception
  when exclusion_violation then
    raise exception 'Ce créneau vient d’être réservé par une autre personne.';
end;
$function$;

CREATE OR REPLACE FUNCTION public.update_public_booking_settings(p_organization_id uuid, p_enabled boolean, p_confirmation_mode text, p_slot_interval integer, p_min_notice_hours integer, p_max_days_ahead integer, p_cancel_notice_hours integer, p_welcome_text text DEFAULT NULL::text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if auth.uid() is null then
    raise exception 'Authentification requise.';
  end if;

  if not public.has_org_role(p_organization_id, array['owner','admin','manager']) then
    raise exception 'Vous ne disposez pas des droits nécessaires.';
  end if;

  if p_confirmation_mode not in ('automatic','manual') then
    raise exception 'Mode de confirmation invalide.';
  end if;

  if p_slot_interval not in (5,10,15,20,30,45,60) then
    raise exception 'Intervalle de créneau invalide.';
  end if;

  if p_min_notice_hours not between 0 and 720 then
    raise exception 'Délai minimum invalide.';
  end if;

  if p_max_days_ahead not between 1 and 365 then
    raise exception 'Période de réservation invalide.';
  end if;

  if p_cancel_notice_hours not between 0 and 720 then
    raise exception 'Délai d’annulation invalide.';
  end if;

  update public.organizations
  set booking_enabled = p_enabled,
      booking_confirmation_mode = p_confirmation_mode,
      booking_slot_interval = p_slot_interval,
      booking_min_notice_hours = p_min_notice_hours,
      booking_max_days_ahead = p_max_days_ahead,
      booking_cancel_notice_hours = p_cancel_notice_hours,
      booking_welcome_text = nullif(trim(coalesce(p_welcome_text, '')), ''),
      updated_at = now()
  where id = p_organization_id;

  insert into public.audit_logs (organization_id, user_id, action, entity_type, entity_id)
  values (p_organization_id, auth.uid(), 'booking.settings_updated', 'organization', p_organization_id::text);
end;
$function$;

CREATE OR REPLACE FUNCTION public.get_public_available_slots(p_slug text, p_service_id uuid, p_date date, p_staff_id uuid DEFAULT NULL::uuid)
 RETURNS TABLE(slot_start timestamp with time zone, slot_end timestamp with time zone, staff_id uuid, staff_name text)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_organization_id uuid;
  v_timezone text;
  v_interval integer;
  v_min_notice integer;
  v_max_days integer;
  v_duration integer;
  v_today date;
  v_weekday smallint;
begin
  select id, timezone, booking_slot_interval, booking_min_notice_hours, booking_max_days_ahead
  into v_organization_id, v_timezone, v_interval, v_min_notice, v_max_days
  from public.organizations
  where slug = lower(trim(p_slug))
    and status in ('trial','active')
    and business_type = 'coiffure'
    and booking_enabled = true;

  if v_organization_id is null then
    return;
  end if;

  select duration_minutes into v_duration
  from public.services
  where id = p_service_id
    and organization_id = v_organization_id
    and active = true;

  if v_duration is null then
    return;
  end if;

  v_today := (now() at time zone v_timezone)::date;
  if p_date < v_today or p_date > v_today + v_max_days then
    return;
  end if;

  v_weekday := extract(isodow from p_date)::smallint - 1;

  return query
  with candidates as (
    select
      st.id as candidate_staff_id,
      st.display_name as candidate_staff_name,
      local_start,
      local_start + make_interval(mins => v_duration) as local_end
    from public.staff st
    join public.staff_services ss
      on ss.organization_id = st.organization_id
     and ss.staff_id = st.id
     and ss.service_id = p_service_id
    join public.staff_working_hours h
      on h.organization_id = st.organization_id
     and h.staff_id = st.id
     and h.weekday = v_weekday
    cross join lateral generate_series(
      p_date + h.start_time,
      p_date + h.end_time - make_interval(mins => v_duration),
      make_interval(mins => v_interval)
    ) as local_start
    where st.organization_id = v_organization_id
      and st.active = true
      and (p_staff_id is null or st.id = p_staff_id)
  )
  select
    c.local_start at time zone v_timezone as slot_start,
    c.local_end at time zone v_timezone as slot_end,
    c.candidate_staff_id as staff_id,
    c.candidate_staff_name as staff_name
  from candidates c
  where (c.local_start at time zone v_timezone) >= now() + make_interval(hours => v_min_notice)
    and not exists (
      select 1
      from public.staff_breaks b
      where b.organization_id = v_organization_id
        and b.staff_id = c.candidate_staff_id
        and b.weekday = v_weekday
        and c.local_start::time < b.end_time
        and c.local_end::time > b.start_time
    )
    and not exists (
      select 1
      from public.appointments a
      where a.organization_id = v_organization_id
        and a.staff_id = c.candidate_staff_id
        and a.status <> 'cancelled'
        and tstzrange(a.starts_at, a.ends_at, '[)') && tstzrange(
          c.local_start at time zone v_timezone,
          c.local_end at time zone v_timezone,
          '[)'
        )
    )
  order by slot_start, staff_name;
end;
$function$;

CREATE OR REPLACE FUNCTION public.get_public_available_slots_v2(p_slug text, p_site_id uuid, p_service_id uuid, p_date date, p_staff_id uuid DEFAULT NULL::uuid)
 RETURNS TABLE(slot_start timestamp with time zone, slot_end timestamp with time zone, staff_id uuid, staff_name text)
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public', 'pg_catalog'
AS $function$
declare
  v_company_page jsonb;
  v_organization_id uuid;
  v_plan text;
  v_timezone text;
  v_interval integer;
  v_min_notice integer;
  v_max_days integer;
  v_duration integer;
  v_today date;
  v_weekday smallint;
begin
  v_company_page := public.get_public_metier_coiffure_company_page(p_slug);
  if v_company_page is not null then
    return query
    select s.slot_start,s.slot_end,s.staff_id,s.staff_name
    from public.get_public_metier_coiffure_company_slots_v2(p_slug,p_site_id,p_service_id,p_date,p_staff_id) s;
    return;
  end if;

  select id,plan,timezone,booking_slot_interval,booking_min_notice_hours,booking_max_days_ahead
  into v_organization_id,v_plan,v_timezone,v_interval,v_min_notice,v_max_days
  from public.organizations
  where slug=lower(trim(p_slug)) and status in ('trial','active') and business_type='coiffure' and booking_enabled=true;
  if v_organization_id is null then return; end if;

  if v_plan='metier' and not exists (
    select 1 from public.organization_sites
    where id=p_site_id and organization_id=v_organization_id and status='active'
  ) then return; end if;
  if v_plan='metier' then
    select timezone into v_timezone
    from public.organization_sites
    where id=p_site_id and organization_id=v_organization_id and status='active';
  end if;

  select duration_minutes into v_duration
  from public.services
  where id=p_service_id and organization_id=v_organization_id and active=true;
  if v_duration is null then return; end if;

  v_today := (now() at time zone v_timezone)::date;
  if p_date<v_today or p_date>v_today+v_max_days then return; end if;
  v_weekday := extract(isodow from p_date)::smallint-1;

  return query
  with candidates as (
    select st.id candidate_staff_id,st.display_name candidate_staff_name,
           local_start,local_start+make_interval(mins=>v_duration) local_end
    from public.staff st
    join public.staff_services ss
      on ss.organization_id=st.organization_id and ss.staff_id=st.id and ss.service_id=p_service_id
    join public.staff_working_hours h
      on h.organization_id=st.organization_id and h.staff_id=st.id and h.weekday=v_weekday
    cross join lateral generate_series(
      p_date+h.start_time,
      p_date+h.end_time-make_interval(mins=>v_duration),
      make_interval(mins=>v_interval)
    ) gs(local_start)
    where st.organization_id=v_organization_id
      and st.active=true
      and (v_plan<>'metier' or st.site_id=p_site_id)
      and (p_staff_id is null or st.id=p_staff_id)
  )
  select c.local_start at time zone v_timezone,c.local_end at time zone v_timezone,
         c.candidate_staff_id,c.candidate_staff_name
  from candidates c
  where (c.local_start at time zone v_timezone)>=now()+make_interval(hours=>v_min_notice)
    and not exists (
      select 1 from public.staff_breaks b
      where b.organization_id=v_organization_id
        and b.staff_id=c.candidate_staff_id
        and b.weekday=v_weekday
        and c.local_start::time<b.end_time
        and c.local_end::time>b.start_time
    )
    and not exists (
      select 1 from public.appointments a
      where a.organization_id=v_organization_id
        and a.staff_id=c.candidate_staff_id
        and a.status<>'cancelled'
        and tstzrange(a.starts_at,a.ends_at,'[)') &&
            tstzrange(c.local_start at time zone v_timezone,c.local_end at time zone v_timezone,'[)')
    )
  order by slot_start,staff_name;
end;
$function$;

CREATE OR REPLACE FUNCTION public.resend_coiffure_client_portal_invitation(p_organization_id uuid, p_invitation_id uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare v_token text; v_id uuid;
begin
  if auth.uid() is null or not public.has_org_role(p_organization_id,array['owner','admin','manager']) then raise exception 'Droits insuffisants.'; end if;
  v_token:=encode(extensions.gen_random_bytes(32),'hex');
  update public.coiffure_client_portal_invitations
  set token_hash=extensions.digest(v_token,'sha256'),status='pending',expires_at=now()+interval '7 days',revoked_at=null,updated_at=now()
  where organization_id=p_organization_id and id=p_invitation_id and status in ('pending','expired')
  returning id into v_id;
  if v_id is null then raise exception 'Invitation introuvable.'; end if;
  perform public.enqueue_coiffure_client_portal_invitation_email(v_id,v_token);
end;
$function$;
