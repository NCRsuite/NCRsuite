import fs from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { build } from 'esbuild';
import postcss from 'postcss';
import * as React from 'react';
import * as jsx from 'react/jsx-runtime';
const base = 'src/components/public-home';
const scope = '#ncr-public-home';
const sourceCss = (await fs.readFile(`${base}/styles.source.css`, 'utf8'))
  .replace('.product-carousel.is-pinned{height:360vh}', '.product-carousel.is-pinned{height:332dvh}')
  .replace('.is-pinned .product-sticky{flex-direction:column;height:100svh', '.is-pinned .product-sticky{flex-direction:column;height:100dvh')
  .replaceAll('--tw-', '--ncr-home-tw-')
  .replaceAll('Inter', 'NCRHomeInter');
const root = postcss.parse(sourceCss);
root.walkAtRules('layer', rule => { if (rule.nodes) rule.replaceWith(...rule.nodes); else rule.remove(); });
root.walkAtRules('font-face', rule => rule.remove()); // Existing Inter font, already served by NCR Suite.
const animations = new Map();
root.walkAtRules('keyframes', rule => { const old = rule.params; const name = `ncr-home-${old}`; animations.set(old, name); rule.params = name; });
root.walkDecls(decl => { if (decl.prop.startsWith('animation')) for (const [old, name] of animations) decl.value = decl.value.replace(new RegExp(`\\b${old}\\b`, 'g'), name); });
root.walkRules(rule => {
  for (let parent = rule.parent; parent; parent = parent.parent) if (parent.type === 'rule' || (parent.type === 'atrule' && parent.name.includes('keyframes'))) return;
  rule.selectors = rule.selectors.map(selector => {
    if ([':root', ':host', 'html', 'body'].includes(selector)) return scope;
    return `${scope} ${selector}`;
  });
});
root.append('@font-face { font-family:NCRHomeInter; src:url("/fonts/inter-variable.woff2") format("woff2"); font-weight:100 900; font-style:normal; font-display:swap; }');
// Match the prototype's document scrolling only while this landing is mounted.
// overflow:hidden on the SaaS ancestors otherwise captures position:sticky.
root.append(`html:has(${scope}), body:has(${scope}), #root:has(${scope}) { overflow-x:clip; overflow-y:visible; }`);
root.append(`${scope} { font-feature-settings:normal; display:block; font-family:NCRHomeInter,ui-sans-serif,system-ui,sans-serif; line-height:1.5; color:#0b0d12; background:#f4f6fa; overflow-x:clip; }`);
await fs.writeFile(`${base}/styles.scoped.css`, root.toString());
const result = await build({entryPoints:[`${base}/runtime.tsx`],bundle:true,format:'esm',platform:'browser',target:'es2020',jsx:'automatic',minify:true,write:false,define:{'process.env.NODE_ENV':'"production"'},plugins:[{name:'shared-app-react',setup(builder){
 builder.onResolve({filter:/^react(?:\/jsx-runtime)?$/},args=>({path:args.path,namespace:'shared-react'}));
 builder.onLoad({filter:/.*/,namespace:'shared-react'},args=>{
  const source=args.path==='react'?'React':'jsx';
  const names=Object.keys(source==='React'?React:jsx).filter(name=>name!=='default' && /^[a-zA-Z_$][\w$]*$/.test(name));
  return {contents:`const api=globalThis[Symbol.for('ncr.public-home.react')].${source};\n`+names.map(name=>`export const ${name}=api.${name};`).join('\n')+'\nexport default api;',loader:'js'};
 });
}},{name:'inline-scoped-css',setup(builder){builder.onResolve({filter:/styles\.scoped\.css\?inline$/},args=>({path:path.resolve(args.resolveDir,'styles.scoped.css'),namespace:'home-css'}));builder.onLoad({filter:/.*/,namespace:'home-css'},async args=>({contents:await fs.readFile(args.path,'utf8'),loader:'text'}));}}]});
const bytes=result.outputFiles[0].contents;
const hash=createHash('sha256').update(bytes).digest('hex').slice(0,16);
await fs.mkdir('public/public-home',{recursive:true});
for (const file of await fs.readdir('public/public-home')) if (/^runtime-[a-f0-9]+\.js$/.test(file)) await fs.unlink(`public/public-home/${file}`);
await fs.writeFile(`public/public-home/runtime-${hash}.js`,bytes);
await fs.writeFile(`${base}/moduleUrl.ts`,`// Generated by scripts/build-public-home.mjs\nexport const publicHomeModuleUrl = '/public-home/runtime-${hash}.js';\n`);
console.log(`Public home: isolated module ${hash}, ${bytes.length} bytes; application build unchanged.`);
